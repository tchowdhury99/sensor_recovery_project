def infer_baseline_name(text):
    baselines = [
        "baseline_01_hover",
        "baseline_02_high_altitude_hover",
        "baseline_03_forward_motion",
        "baseline_04_yaw_rotation",
        "baseline_05_mixed_maneuver",
    ]
    text = str(text)
    for b in baselines:
        if b in text:
            return b
    return None


def safe_div(num, den):
    if den == 0:
        return np.nan
    return float(num) / float(den)


def compute_metrics(y_true, y_pred):
    y_true = np.asarray(y_true).astype(int)
    y_pred = np.asarray(y_pred).astype(int)

    m = min(len(y_true), len(y_pred))
    y_true = y_true[:m]
    y_pred = y_pred[:m]

    TP = int(np.sum((y_true == 1) & (y_pred == 1)))
    FP = int(np.sum((y_true == 0) & (y_pred == 1)))
    TN = int(np.sum((y_true == 0) & (y_pred == 0)))
    FN = int(np.sum((y_true == 1) & (y_pred == 0)))

    precision = safe_div(TP, TP + FP)
    recall = safe_div(TP, TP + FN)

    if np.isfinite(precision) and np.isfinite(recall) and (precision + recall) > 0:
        f1 = 2.0 * precision * recall / (precision + recall)
    else:
        f1 = np.nan

    fpr = safe_div(FP, FP + TN)

    return {
        "TP": TP,
        "FP": FP,
        "TN": TN,
        "FN": FN,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "false_positive_rate": fpr,
    }


def compute_detection_delay(y_true, y_pred):
    y_true = np.asarray(y_true).astype(int)
    y_pred = np.asarray(y_pred).astype(int)

    attack_indices = np.where(y_true == 1)[0]

    if len(attack_indices) == 0:
        return np.nan

    attack_start = attack_indices[0]

    detection_indices = np.where(
        (np.arange(len(y_pred)) >= attack_start) & (y_pred == 1)
    )[0]

    if len(detection_indices) == 0:
        return np.nan

    return int(detection_indices[0] - attack_start)


def window_detect(abs_residual, threshold_array, W=10, N=3):
    """
    abs_residual: array
    threshold_array: scalar or array of same length

    Point exceedance:
        exceed[k] = abs_residual[k] > threshold[k]

    Window detection:
        flag[k] = 1 if sum(exceed[k-W+1:k]) >= N
    """
    abs_residual = np.asarray(abs_residual, dtype=float)

    if np.isscalar(threshold_array):
        threshold_array = np.full(len(abs_residual), float(threshold_array))
    else:
        threshold_array = np.asarray(threshold_array, dtype=float)

    m = min(len(abs_residual), len(threshold_array))
    abs_residual = abs_residual[:m]
    threshold_array = threshold_array[:m]

    exceed = (abs_residual > threshold_array).astype(int)

    window_count = (
        pd.Series(exceed)
        .rolling(window=W, min_periods=1)
        .sum()
        .to_numpy()
    )

    window_flag = (window_count >= N).astype(int)

    return exceed, window_count, window_flag, threshold_array


def find_xkf1_file(baseline):
    """
    Finds XKF1 CSV file for a baseline.
    """
    patterns = [
        f"*{baseline}*XKF1*.csv",
        f"*{baseline}*xkf1*.csv",
        f"*{baseline}*XKF*.csv",
        f"*{baseline}*xkf*.csv",
    ]

    candidates = []
    for pat in patterns:
        candidates.extend(sorted(CLEAN_DIR.rglob(pat)))

    # Remove duplicates while preserving order.
    seen = set()
    unique = []
    for p in candidates:
        if p not in seen:
            seen.add(p)
            unique.append(p)

    if not unique:
        return None

    return unique[0]


def nearest_xkf1_rows_by_time(att_timeus, xkf_df):
    """
    Returns nearest XKF1 row indices for each ATT TimeUS.
    """
    if "TimeUS" not in xkf_df.columns:
        return None

    xkf_time = pd.to_numeric(xkf_df["TimeUS"], errors="coerce").to_numpy(dtype=float)
    att_time = np.asarray(att_timeus, dtype=float)

    finite_xkf = np.isfinite(xkf_time)
    if finite_xkf.sum() < 2:
        return None

    xkf_time_valid = xkf_time[finite_xkf]
    xkf_indices_valid = np.where(finite_xkf)[0]

    order = np.argsort(xkf_time_valid)
    xkf_time_sorted = xkf_time_valid[order]
    xkf_indices_sorted = xkf_indices_valid[order]

    pos = np.searchsorted(xkf_time_sorted, att_time)

    pos_left = np.clip(pos - 1, 0, len(xkf_time_sorted) - 1)
    pos_right = np.clip(pos, 0, len(xkf_time_sorted) - 1)

    left_diff = np.abs(att_time - xkf_time_sorted[pos_left])
    right_diff = np.abs(att_time - xkf_time_sorted[pos_right])

    choose_right = right_diff < left_diff
    nearest_pos = np.where(choose_right, pos_right, pos_left)

    return xkf_indices_sorted[nearest_pos]


def get_att_timeus_for_segment(segment_df):
    """
    Reconstructs absolute ATT TimeUS for an aligned segment using:
      CleanFile
      AlignmentOffset
      length of segment

    The corrected detector aligned prediction[i] with clean ATT row offset + 1 + i.
    """
    if "CleanFile" not in segment_df.columns:
        return None

    if "AlignmentOffset" not in segment_df.columns:
        return None

    clean_file = Path(str(segment_df["CleanFile"].iloc[0]))
    offset = int(segment_df["AlignmentOffset"].iloc[0])
    n = len(segment_df)

    if not clean_file.exists():
        return None

    clean_df = pd.read_csv(clean_file)

    if "TimeUS" not in clean_df.columns:
        return None

    start = offset + 1
    end = start + n

    if end > len(clean_df):
        end = len(clean_df)

    att_time = pd.to_numeric(clean_df["TimeUS"], errors="coerce").to_numpy(dtype=float)
    att_time_segment = att_time[start:end]

    if len(att_time_segment) != n:
        m = min(len(att_time_segment), n)
        return att_time_segment[:m]

    return att_time_segment


def compute_dynamic_threshold(segment_df, axis):
    """
    Computes dynamic threshold for Roll/Pitch using XKF1 VN/VE.

    For Yaw:
        returns static global Yaw threshold array.
    """
    n = len(segment_df)
    baseline = str(segment_df["Baseline"].iloc[0]) if "Baseline" in segment_df.columns else infer_baseline_name(segment_df)

    if axis == "Yaw":
        return np.full(n, STATIC_GLOBAL["Yaw"]), "yaw_static_global", "Yaw uses conservative static global threshold"

    if axis not in ["Roll", "Pitch"]:
        return np.full(n, STATIC_GLOBAL.get(axis, np.nan)), "fallback_static_global", "Unsupported axis"

    xkf_path = find_xkf1_file(baseline)

    if xkf_path is None:
        return (
            np.full(n, STATIC_GLOBAL[axis]),
            "dynamic_xkf1_missing_fallback_static_global",
            "No XKF1 file found; used static global fallback",
        )

    xkf_df = pd.read_csv(xkf_path)

    required = ["VN", "VE"]
    missing = [c for c in required if c not in xkf_df.columns]

    if missing:
        return (
            np.full(n, STATIC_GLOBAL[axis]),
            "dynamic_xkf1_missing_columns_fallback_static_global",
            f"XKF1 file missing columns {missing}; used static global fallback",
        )

    att_timeus = get_att_timeus_for_segment(segment_df)

    if att_timeus is None:
        return (
            np.full(n, STATIC_GLOBAL[axis]),
            "dynamic_xkf1_no_time_alignment_fallback_static_global",
            "Could not reconstruct ATT TimeUS; used static global fallback",
        )

    nearest_idx = nearest_xkf1_rows_by_time(att_timeus, xkf_df)

    if nearest_idx is None:
        return (
            np.full(n, STATIC_GLOBAL[axis]),
            "dynamic_xkf1_bad_time_fallback_static_global",
            "Could not align XKF1 by TimeUS; used static global fallback",
        )

    nearest_idx = nearest_idx[:n]

    vn = pd.to_numeric(xkf_df.loc[nearest_idx, "VN"], errors="coerce").to_numpy(dtype=float)
    ve = pd.to_numeric(xkf_df.loc[nearest_idx, "VE"], errors="coerce").to_numpy(dtype=float)

    horizontal_speed = np.sqrt(vn ** 2 + ve ** 2)

    alpha_speed = np.clip(
        (horizontal_speed - 0.5) / (2.0 - 0.5),
        0.0,
        1.0,
    )

    if axis == "Roll":
        T_hover = DYNAMIC_ROLL["T_hover"]
        T_high = DYNAMIC_ROLL["T_high"]
    else:
        T_hover = DYNAMIC_PITCH["T_hover"]
        T_high = DYNAMIC_PITCH["T_high"]

    dynamic_threshold = T_hover + alpha_speed * (T_high - T_hover)

    # If any NaN appears, replace with static global as conservative fallback.
    dynamic_threshold = np.where(
        np.isfinite(dynamic_threshold),
        dynamic_threshold,
        STATIC_GLOBAL[axis],
    )

    note = f"XKF1 dynamic threshold from {xkf_path}"

    return dynamic_threshold, "dynamic_xkf1", note


def plot_threshold_comparison(
    fig_path,
    x,
    abs_residual,
    attack_active,
    flags_dict,
    thresholds_dict,
    title,
):
    """
    Creates a comparison figure:
    1. abs residual vs thresholds
    2. detection flags vs AttackActive
    """
    fig = plt.figure(figsize=(14, 8))

    ax1 = fig.add_subplot(2, 1, 1)
    ax1.plot(x, abs_residual, label="|Residual|")

    for method, T in thresholds_dict.items():
        if np.isscalar(T):
            ax1.plot(x, np.full(len(x), T), linestyle="--", label=f"{method} threshold")
        else:
            ax1.plot(x, T[:len(x)], linestyle="--", label=f"{method} threshold")

    ax1.set_ylabel("|Residual|")
    ax1.grid(True, alpha=0.3)
    ax1.legend(loc="best")

    ax2 = fig.add_subplot(2, 1, 2)
    ax2.step(x, attack_active, where="post", label="AttackActive")

    for method, flag in flags_dict.items():
        ax2.step(x, flag[:len(x)], where="post", label=f"{method} detection", alpha=0.8)

    ax2.set_ylabel("Detection flag")
    ax2.set_xlabel("Aligned segment time/sample")
    ax2.set_ylim(-0.1, 1.2)
    ax2.grid(True, alpha=0.3)
    ax2.legend(loc="best")

    fig.suptitle(title)
    fig.tight_layout(rect=[0, 0.03, 1, 0.95])
    fig.savefig(fig_path, dpi=160)
    plt.close(fig)


