def main():
    segment_files = sorted(ALIGNED_SEGMENT_DIR.glob("*_aligned_attacked_segment.csv"))

    if not segment_files:
        raise FileNotFoundError(
            f"No aligned attacked segment CSV files found in {ALIGNED_SEGMENT_DIR}. "
            "Run phase4_detect_attacks_v9_corrected.py first."
        )

    print(f"[INFO] Found {len(segment_files)} aligned attacked segment files.")

    summary_rows = []

    for seg_path in segment_files:
        seg = pd.read_csv(seg_path)

        if len(seg) == 0:
            print(f"[WARN] Empty segment: {seg_path}")
            continue

        baseline = str(seg["Baseline"].iloc[0])
        axis = str(seg["Axis"].iloc[0])
        attack_type = str(seg["AttackType"].iloc[0])

        residual_col = f"Residual_{axis}"
        abs_residual_col = f"AbsResidual_{axis}"

        if abs_residual_col in seg.columns:
            abs_residual = pd.to_numeric(seg[abs_residual_col], errors="coerce").to_numpy(dtype=float)
        elif residual_col in seg.columns:
            abs_residual = np.abs(pd.to_numeric(seg[residual_col], errors="coerce").to_numpy(dtype=float))
        else:
            print(f"[WARN] Missing residual column for {seg_path}")
            continue

        attack_active = pd.to_numeric(seg["AttackActive"], errors="coerce").fillna(0).astype(int).to_numpy()

        if "x" in seg.columns:
            x = pd.to_numeric(seg["x"], errors="coerce").to_numpy(dtype=float)
            if len(x) != len(seg) or not np.isfinite(x).all():
                x = np.arange(len(seg))
        else:
            x = np.arange(len(seg))

        # Method 1: static global threshold.
        T_static_global = np.full(len(seg), STATIC_GLOBAL[axis])

        # Method 2: scenario-specific threshold.
        if "Threshold_p99_abs" in seg.columns:
            scenario_threshold_value = float(seg["Threshold_p99_abs"].iloc[0])
        else:
            scenario_threshold_value = STATIC_GLOBAL[axis]

        T_scenario = np.full(len(seg), scenario_threshold_value)

        # Method 3: XKF1 dynamic threshold for Roll/Pitch, Yaw fallback static.
        T_dynamic, dynamic_method_name, dynamic_note = compute_dynamic_threshold(seg, axis)

        methods = {
            "static_global": T_static_global,
            "scenario_specific": T_scenario,
            "dynamic_xkf1" if axis in ["Roll", "Pitch"] else "yaw_static_global": T_dynamic,
        }

        flags_for_plot = {}
        thresholds_for_plot = {}

        comparison_df = pd.DataFrame({
            "x": x,
            "Baseline": baseline,
            "Axis": axis,
            "AttackType": attack_type,
            "AttackActive": attack_active,
            "AbsResidual": abs_residual,
        })

        for method_name, T in methods.items():
            exceed, window_count, window_flag, T_array = window_detect(
                abs_residual=abs_residual,
                threshold_array=T,
                W=W,
                N=N,
            )

            comparison_df[f"Threshold_{method_name}"] = T_array
            comparison_df[f"PointExceed_{method_name}"] = exceed
            comparison_df[f"WindowCount_{method_name}"] = window_count
            comparison_df[f"WindowDetection_{method_name}"] = window_flag

            flags_for_plot[method_name] = window_flag
            thresholds_for_plot[method_name] = T_array

            metrics = compute_metrics(attack_active, window_flag)
            delay = compute_detection_delay(attack_active, window_flag)

            summary_rows.append({
                "baseline": baseline,
                "axis": axis,
                "attack_type": attack_type,
                "threshold_method": method_name,
                "dynamic_method_detail": dynamic_method_name if method_name.startswith("dynamic") or method_name.startswith("yaw") else "",
                "dynamic_note": dynamic_note if method_name.startswith("dynamic") or method_name.startswith("yaw") else "",
                "W": W,
                "N": N,
                "TP": metrics["TP"],
                "FP": metrics["FP"],
                "TN": metrics["TN"],
                "FN": metrics["FN"],
                "precision": metrics["precision"],
                "recall": metrics["recall"],
                "f1": metrics["f1"],
                "false_positive_rate": metrics["false_positive_rate"],
                "detection_delay_samples": delay,
                "n_eval_samples": len(seg),
                "input_segment_csv": str(seg_path),
            })

        out_csv = OUT_CSV_DIR / f"{baseline}_{axis}_{attack_type}_threshold_method_comparison.csv"
        comparison_df.to_csv(out_csv, index=False)

        fig_path = FIG_DIR / f"{baseline}_{axis}_{attack_type}_threshold_method_comparison.png"
        title = f"{baseline} | {axis} | {attack_type} | Threshold Method Comparison"

        plot_threshold_comparison(
            fig_path=fig_path,
            x=x,
            abs_residual=abs_residual,
            attack_active=attack_active,
            flags_dict=flags_for_plot,
            thresholds_dict=thresholds_for_plot,
            title=title,
        )

        print(f"[OK] {baseline} | {axis} | {attack_type}")

    summary = pd.DataFrame(summary_rows)

    summary_path = REPORT_DIR / "phase4b_threshold_method_comparison_v9.csv"
    summary.to_csv(summary_path, index=False)

    # Aggregate report.
    lines = []
    lines.append("PHASE 4B THRESHOLD METHOD COMPARISON REPORT")
    lines.append("=" * 70)
    lines.append("")
    lines.append(f"Input aligned segment folder: {ALIGNED_SEGMENT_DIR}")
    lines.append(f"Output comparison CSV folder: {OUT_CSV_DIR}")
    lines.append(f"Output figure folder: {FIG_DIR}")
    lines.append(f"Summary CSV: {summary_path}")
    lines.append("")
    lines.append(f"Rows in summary: {len(summary)}")
    lines.append("")

    if len(summary) > 0:
        method_summary = (
            summary.groupby("threshold_method")
            .agg(
                mean_precision=("precision", "mean"),
                mean_recall=("recall", "mean"),
                mean_f1=("f1", "mean"),
                mean_fpr=("false_positive_rate", "mean"),
                median_delay=("detection_delay_samples", "median"),
                n_rows=("threshold_method", "size"),
            )
            .reset_index()
            .sort_values(["mean_f1", "mean_fpr", "median_delay"], ascending=[False, True, True])
        )

        lines.append("Overall threshold-method comparison:")
        lines.append(method_summary.to_string(index=False))
        lines.append("")

        attack_summary = (
            summary.groupby(["threshold_method", "attack_type"])
            .agg(
                mean_precision=("precision", "mean"),
                mean_recall=("recall", "mean"),
                mean_f1=("f1", "mean"),
                mean_fpr=("false_positive_rate", "mean"),
                median_delay=("detection_delay_samples", "median"),
                n_rows=("attack_type", "size"),
            )
            .reset_index()
            .sort_values(["threshold_method", "mean_f1"], ascending=[True, False])
        )

        lines.append("Threshold method by attack type:")
        lines.append(attack_summary.to_string(index=False))
        lines.append("")

        axis_summary = (
            summary.groupby(["threshold_method", "axis"])
            .agg(
                mean_precision=("precision", "mean"),
                mean_recall=("recall", "mean"),
                mean_f1=("f1", "mean"),
                mean_fpr=("false_positive_rate", "mean"),
                median_delay=("detection_delay_samples", "median"),
                n_rows=("axis", "size"),
            )
            .reset_index()
            .sort_values(["threshold_method", "mean_f1"], ascending=[True, False])
        )

        lines.append("Threshold method by axis:")
        lines.append(axis_summary.to_string(index=False))
        lines.append("")

        best = method_summary.iloc[0]

        lines.append("Recommended threshold method:")
        lines.append(f"- {best['threshold_method']}")
        lines.append(f"- mean precision: {best['mean_precision']:.4f}")
        lines.append(f"- mean recall: {best['mean_recall']:.4f}")
        lines.append(f"- mean F1: {best['mean_f1']:.4f}")
        lines.append(f"- mean FPR: {best['mean_fpr']:.4f}")
        lines.append(f"- median detection delay: {best['median_delay']}")
        lines.append("")

        lines.append("Phase 4B decision rule:")
        lines.append("- Prefer the method with the highest mean F1.")
        lines.append("- If two methods are close, prefer lower false positive rate.")
        lines.append("- If still close, prefer lower detection delay.")
        lines.append("")

        if best["mean_recall"] >= 0.80 and best["mean_fpr"] <= 0.05:
            lines.append("Decision:")
            lines.append("- Phase 4B threshold-method comparison is acceptable.")
            lines.append("- You may carry the recommended method into Phase 5 recovery.")
        else:
            lines.append("Decision:")
            lines.append("- Phase 4B needs inspection before Phase 5.")
            if best["mean_recall"] < 0.80:
                lines.append("- Reason: best mean recall is below 0.80.")
            if best["mean_fpr"] > 0.05:
                lines.append("- Reason: best mean FPR is above 0.05.")

    report_path = REPORT_DIR / "phase4b_threshold_method_comparison_v9.txt"
    report_path.write_text("\n".join(lines))

    print()
    print("[DONE] Phase 4B threshold comparison complete.")
    print(f"[SUMMARY CSV] {summary_path}")
    print(f"[REPORT TXT]  {report_path}")
    print(f"[CSV DIR]     {OUT_CSV_DIR}")
    print(f"[FIG DIR]     {FIG_DIR}")

    if len(summary) > 0:
        print()
        print("[OVERALL METHOD SUMMARY]")
        print(method_summary.to_string(index=False))


if __name__ == "__main__":
    main()