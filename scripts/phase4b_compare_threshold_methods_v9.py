#!/usr/bin/env python3

"""
Phase 4B: Compare threshold methods for corrected V9 attack detection.

This script does NOT redo V9 training.
This script does NOT redo Phase 3.
This script does NOT perform recovery.

It reads the corrected Phase 4 aligned attacked segments generated by:
    phase4_detect_attacks_v9_corrected.py

Then it compares three threshold strategies:

1. static_global:
   One conservative threshold per axis:
      Roll  = 0.010307
      Pitch = 0.016190
      Yaw   = 0.013596

2. scenario_specific:
   Uses the scenario/baseline-specific threshold already stored in each aligned segment:
      Threshold_p99_abs

3. dynamic_xkf1:
   For Roll/Pitch only:
      horizontal_speed = sqrt(VN^2 + VE^2)
      alpha_speed = clip((horizontal_speed - 0.5) / (2.0 - 0.5), 0, 1)
      T_axis[k] = T_hover_axis + alpha_speed[k] * (T_high_axis - T_hover_axis)

   Roll:
      T_hover = 0.006865
      T_high  = 0.010307

   Pitch:
      T_hover = 0.009161
      T_high  = 0.016190

   For Yaw:
      dynamic method falls back to conservative static global Yaw threshold:
      T_yaw = 0.013596

Window rule:
   W = 10, N = 3
   Detection if at least 3 of the last 10 samples exceed threshold.

Outputs:
   - Per-file comparison CSVs
   - Summary CSV
   - Text interpretation report
   - Comparison figures
"""

